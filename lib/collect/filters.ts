// 수집 제외 필터 — 사진/화보 등 본문 없는 기사
//  예: "[포토] ...", "[화보] ...", "[사진] ...", "포토뉴스" 등
const PHOTO_RE = /\[\s*(포토|포토뉴스|화보|화보컷|사진|셀럽샷|셀럽|스타샷|포토컷|움짤|그래픽|인포그래픽|만평|카드뉴스|일러스트|영상화보)\s*\]|^\s*(포토|포토뉴스|화보|셀럽샷)\b/;

/** 사진/화보 위주(본문 없는) 기사면 true → 수집 제외 */
export function isPhotoOnlyTitle(title: string): boolean {
  return PHOTO_RE.test(title || "");
}

// 칼럼·오피니언·연재물(범죄/재판 기사가 아닌 논평·에세이) — 제목 머리표 기준
const COLUMN_RE = /\[[^\]]*(칼럼|경영학|경제학|에세이|연재|시론|기고|사설|오피니언|단상|시평|논단|기자수첩|데스크|문화산책|인문학|북리뷰|서평|살롱|매거진|트렌드|라이프|레시피|건강|여행|스포츠|연예|영화|드라마|리뷰)[^\]]*\]/;

/** 칼럼·오피니언·연재물이면 true → 수집 제외(범죄/재판 보도 아님) */
export function isOpinionColumn(title: string): boolean {
  return COLUMN_RE.test(title || "");
}

// 한국 관할 단서(한국 지명·기관·한국인 등). 하나라도 있으면 국내/한국인 관련 사건으로 간주.
//  ※ 한국인이 외국에서 일으킨 사건은 '한국/한국인/한인/국적' 등 단서가 있어 포함됨.
