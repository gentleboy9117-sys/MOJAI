    "법무부|행정안전부|국토교통부|기획재정부|고용노동부|보건복지부|외교부|국방부|환경부|해양수산부",
    "민주노총|한국노총|전교조|참여연대|국민의힘|더불어민주당|민주당|정의당|조국혁신당",
    "서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충청|충북|충남|전라|전북|전남|경상|경북|경남|제주",
