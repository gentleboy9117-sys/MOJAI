/**
 * 집회 관련 텍스트 완화.
 *  1) 공통 민감표현 완화(rewriteText) → 2) 집회 전용 치환 추가.
 */
export function softenAssemblyText(text: string): string {
  let out = rewriteText(text).text;
  for (const rule of ASSEMBLY_REWRITE_RULES) {
    out = out.replace(rule.pattern, rule.soft);
  }
  return out;
}
