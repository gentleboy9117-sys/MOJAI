// =====================================================================
// 집회·시위 보도 화면 공용 필터
//  * 과거·역사적 집회 언급(5·18 당시 집회 등)만 있는 기사는 '현재 공안 동향'이
//    아니므로 집회·시위 보도 화면·대시보드 TOP에서 제외한다 (2026-07-28 지시).
// =====================================================================

// 역사적 사건·시대 신호
const HIST_RE =
  /5\s*[·.]\s*18|4\s*[·.]\s*19|6\s*[·.]\s*10|6월\s*항쟁|민주화\s*운동|민주\s*항쟁|계엄군|3\s*[·.]\s*1\s*운동|유신\s*(정권|체제)|일제\s*강점기|독립\s*운동|(19[0-9]{2}|200[0-9])년[^.]{0,14}(집회|시위|당시)/;

// 현재 진행·예정 집회 신호(하나라도 있으면 현재 공안 기사로 인정)
const CURRENT_RE =
  /집회\s*(예정|신고|개최|금지|제한|허가)|(오늘|내일|모레|주말|이번\s*주|이번\s*달)[^.]{0,12}(집회|시위)|집회[가를은]?\s*(열린|열릴|개최|진행|예고|잇따)|시위[가를은]?\s*(열린|열릴|벌어|이어)|경찰\s*추산|참가자\s*\d|행진|촛불\s*집회|맞불|규탄\s*(집회|시위)|시위대|농성|집시법|집회\s*및\s*시위/;

/** 집회·시위 언급이 '역사적 사실 회고'뿐인 기사면 true → 공안(집회) 화면에서 제외 */
export function isHistoricalAssemblyOnly(title: string, summary?: string | null): boolean {
  const t = `${title || ""} ${summary || ""}`;
  if (!/집회|시위/.test(t)) return false;
  return HIST_RE.test(t) && !CURRENT_RE.test(t);
}
